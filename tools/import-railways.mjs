/** Regenerate the railway catalog from an Overpass JSON snapshot.
 * node tools/import-railways.mjs /path/to/railways.json
 * The query lives beside this script; fetching is an explicit offline step.
 */
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {compileRailMap} from '../web/static/world/assets/rail/map-compiler.js';
import {route,parkAvenue,hudson,harlem} from '../web/static/world/assets/rail/network.js';
const bytes=readFileSync(process.argv[2]),input=JSON.parse(bytes);
if(input.remark)throw Error(`Incomplete Overpass response: ${input.remark}`);
const root=new URL('../',import.meta.url),index=JSON.parse(readFileSync(new URL('public/world/world/index.json',root))),b=index.bounds;
const catalog=compileRailMap(input.elements,{bounds:[(b.minTx-1)*256,(b.minTz-1)*256,(b.maxTx+2)*256,(b.maxTz+2)*256],overrides:[route,parkAvenue,hudson,harlem]});
const structures=['surface','tunnel','bridge','cutting'];
const round=(n,d=4)=>Number(n.toFixed(d));
const data={version:1,source:'https://www.openstreetmap.org',license:'ODbL-1.0',timestamp:input.osm3s?.timestamp_osm_base,sha256:createHash('sha256').update(bytes).digest('hex'),stats:catalog.stats,
  routes:catalog.routes.map(r=>({...r,points:r.points.map(p=>[round(p.x),round(p.z),round(p.y,6),round(p.s,6),structures.indexOf(p.structure)])}))};
writeFileSync(new URL('web/static/world/assets/rail/mapped-data.js',root),'// Generated by tools/import-railways.mjs. © OpenStreetMap contributors, ODbL 1.0.\nexport const mappedData = '+JSON.stringify(data)+';\n');
// Preserve source tags, polygon outlines and entrance positions for further
// renderer detail without loading the whole source extract in every worker.
writeFileSync(new URL('web/static/world/assets/rail/map-features.json',root),JSON.stringify({source:data.source,license:data.license,timestamp:data.timestamp,sha256:data.sha256,features:catalog.features,stations:catalog.stations,platforms:catalog.platforms,entrances:catalog.entrances}));
console.log(JSON.stringify(catalog.stats));
const platforms=spawnSync(process.execPath,[new URL('tools/refine-rail-platforms.mjs',root).pathname],{stdio:'inherit'});
if(platforms.status!==0)throw Error('Platform level refinement failed');
const signs=spawnSync(process.execPath,[new URL('tools/index-subway-signs.mjs',root).pathname,process.argv[2]],{stdio:'inherit'});
if(signs.status!==0)throw Error('Subway service sign generation failed');
const roadClearance=spawnSync(process.execPath,[new URL('tools/index-rail-road-clearance.mjs',root).pathname],{stdio:'inherit'});
if(roadClearance.status!==0)throw Error('Rail road clearance generation failed');
const access=spawnSync(process.execPath,[new URL('tools/index-station-access.mjs',root).pathname],{stdio:'inherit'});
if(access.status!==0)throw Error('Station access generation failed');
const footprints=spawnSync(process.execPath,[new URL('tools/index-rail-footprints.mjs',root).pathname],{stdio:'inherit'});
if(footprints.status!==0)throw Error('Railway footprint generation failed');
