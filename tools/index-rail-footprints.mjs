import {writeFileSync} from 'node:fs';
import {surfaceHoles,waterHoles} from '../web/static/world/assets/rail/network.js';
const compact=holes=>holes.map(r=>r.map(p=>p.map(n=>Number(n.toFixed(3)))));
writeFileSync(new URL('../web/static/world/assets/rail/footprints-data.js',import.meta.url),'// Generated by tools/index-rail-footprints.mjs. © OpenStreetMap contributors, ODbL 1.0.\nexport const footprints = '+JSON.stringify({surface:compact(surfaceHoles),water:compact(waterHoles)})+';\n');
console.log(`Indexed ${surfaceHoles.length} surface and ${waterHoles.length} water footprints.`);
