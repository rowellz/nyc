/** Bundle Mapzen Terrarium terrain in the city's metre projection. No runtime network requests.
 * node tools/import-elevation.mjs [cache-directory]
 * USGS 3DEP terrain via https://registry.opendata.aws/terrain-tiles/
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { inflateSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import path from 'node:path';

const cache = process.argv[2] ?? '/tmp/nyc-elevation-tiles';
await mkdir(cache, { recursive: true });
// One tile of padding around the city also covers geometry owned across an edge.
const zoom = 12, step = 64, x0 = -4864, z0 = -14848, width = 193, height = 365;
const scaleX = 111320 * Math.cos(40.75362 * Math.PI / 180);
const tiles = new Map(), sources = [];
function decodePNG(buffer) {
  if (buffer.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a') throw Error('Invalid terrain PNG');
  const chunks = []; let w, h, channels;
  for (let p = 8; p < buffer.length;) {
    const size = buffer.readUInt32BE(p), kind = buffer.toString('ascii', p + 4, p + 8), data = buffer.subarray(p + 8, p + 8 + size);
    if (kind === 'IHDR') {
      w = data.readUInt32BE(0); h = data.readUInt32BE(4); channels = data[9] === 2 ? 3 : data[9] === 6 ? 4 : 0;
      if (w !== 256 || h !== 256 || data[8] !== 8 || !channels || data[12]) throw Error('Unsupported terrain PNG');
    }
    if (kind === 'IDAT') chunks.push(data);
    p += size + 12;
  }
  const raw = inflateSync(Buffer.concat(chunks)), stride = w * channels, pixels = new Uint8Array(h * stride);
  const paeth = (a, b, c) => { const p = a + b - c, da = Math.abs(p - a), db = Math.abs(p - b), dc = Math.abs(p - c); return da <= db && da <= dc ? a : db <= dc ? b : c; };
  for (let y = 0; y < h; y++) {
    const filter = raw[y * (stride + 1)];
    if (filter > 4) throw Error('Unknown PNG filter');
    for (let x = 0; x < stride; x++) {
      const i = y * stride + x, a = x >= channels ? pixels[i - channels] : 0, b = y ? pixels[i - stride] : 0, c = y && x >= channels ? pixels[i - stride - channels] : 0;
      pixels[i] = raw[y * (stride + 1) + x + 1] + [0, a, b, Math.floor((a + b) / 2), paeth(a, b, c)][filter];
    }
  }
  return Array.from({ length: w * h }, (_, i) => pixels[i * channels] * 256 + pixels[i * channels + 1] + pixels[i * channels + 2] / 256 - 32768);
}
function mercator(x, z) {
  const lon = -73.98322 + x / scaleX, lat = (40.75362 - z / 110574) * Math.PI / 180;
  return [(lon + 180) / 360 * 2 ** zoom * 256 - .5, (1 - Math.asinh(Math.tan(lat)) / Math.PI) / 2 * 2 ** zoom * 256 - .5];
}
const lo = mercator(x0, z0), hi = mercator(x0 + (width - 1) * step, z0 + (height - 1) * step);
for (let ty = Math.floor(lo[1] / 256); ty <= Math.floor((hi[1] + 1) / 256); ty++) {
  for (let tx = Math.floor(lo[0] / 256); tx <= Math.floor((hi[0] + 1) / 256); tx++) {
    const url = `https://s3.amazonaws.com/elevation-tiles-prod/terrarium/${zoom}/${tx}/${ty}.png`, file = path.join(cache, `${zoom}-${tx}-${ty}.png`);
    let bytes;
    try { bytes = await readFile(file); } catch (error) {
      if (error.code !== 'ENOENT') throw error;
      const response = await fetch(url); if (!response.ok) throw Error(`${url}: ${response.status}`);
      bytes = Buffer.from(await response.arrayBuffer()); decodePNG(bytes); await writeFile(file, bytes);
    }
    tiles.set(`${tx},${ty}`, decodePNG(bytes));
    sources.push({ url, sha256: createHash('sha256').update(bytes).digest('hex') });
  }
}
const pixel = (x, y) => tiles.get(`${Math.floor(x / 256)},${Math.floor(y / 256)}`)[(y % 256) * 256 + x % 256];
const values = [];
for (let z = 0; z < height; z++) for (let x = 0; x < width; x++) {
  const [px, py] = mercator(x0 + x * step, z0 + z * step), ix = Math.floor(px), iy = Math.floor(py), u = px - ix, v = py - iy;
  const h = (pixel(ix, iy) * (1 - u) + pixel(ix + 1, iy) * u) * (1 - v) + (pixel(ix, iy + 1) * (1 - u) + pixel(ix + 1, iy + 1) * u) * v;
  // Keep the existing water datum (-1.6 m); bathymetry is not walkable terrain.
  values.push(Math.round(Math.max(0, h) * 10));
}
const output = new URL('../web/static/world/assets/elevation-data.js', import.meta.url);
await writeFile(output, `// Generated by tools/import-elevation.mjs; heights in decimetres.\nexport const elevationData = ${JSON.stringify({ x0, z0, step, width, height, values })};\n`);
await writeFile(new URL('../web/static/world/elevation-sources.json', import.meta.url), JSON.stringify({
  source: 'Mapzen Terrain Tiles / USGS 3DEP', attribution: '3DEP terrain data courtesy of the U.S. Geological Survey.',
  registry: 'https://registry.opendata.aws/terrain-tiles/', projection: 'Bryant Park local tangent plane',
  processing: 'Terrarium zoom 12, bilinearly resampled to a 64 metre grid; negative elevations clamped to zero; rounded to decimetres.', sources,
}, null, 2) + '\n');
console.log(`Bundled ${width} × ${height} elevation samples from ${sources.length} tiles.`);
