/** Rebuild authored rail clearance from complete building footprints, independent
 * of streaming order. Re-run before index-rail-footprints after map changes. */
import {existsSync,readFileSync,writeFileSync} from 'node:fs';
import {gunzipSync} from 'node:zlib';
import {parkAvenue,layout} from '../web/static/world/assets/rail/network.js';
import {foundationIndex,buildingFoundation} from '../public/world/assets/foundations.js';
const tiles=new Map();
function buildingsNear(a,b) {
  const found=new Map();
  for(let x=Math.floor(Math.min(a.x,b.x)/256)-1;x<=Math.floor(Math.max(a.x,b.x)/256)+1;x++)
  for(let z=Math.floor(Math.min(a.z,b.z)/256)-1;z<=Math.floor(Math.max(a.z,b.z)/256)+1;z++) {
    const key=`${x}_${z}`;
    if(!tiles.has(key)) {
      const file=new URL(`../public/world/world/tiles/${key}.json.gz`,import.meta.url);
      tiles.set(key,existsSync(file)?JSON.parse(gunzipSync(readFileSync(file))).buildings:[]);
    }
    for(const building of tiles.get(key)??[])found.set(building.id,building);
  }
  return found.values();
}
const result={};
for(const route of [parkAvenue]) {
  const obstacles=new Map(),base=route.baseHeight;
  for(let i=1;i<route.points.length;i++) {
    const a=route.points[i-1],b=route.points[i];
    if(Math.min(base(a.s),base(b.s))<2)continue; // Buried tracks pass below buildings.
    const width=Math.max(layout(route,null,a.s).width,layout(route,null,b.s).width);
    const index=foundationIndex([{width,pts:[[a.x,a.z],[b.x,b.z]]}]);
    for(const building of buildingsNear(a,b)) {
      // Match the renderer's foundation, rather than the unused groundElev tag.
      // 0.6 m roof parapet + 1 m deck depth + 0.2 m visible separation.
      const height=buildingFoundation(building)+building.height+1.8;
      if(!buildingFoundation(building,index))continue;
      const entry=obstacles.get(building.id)??{buildingId:building.id,start:a.s,end:b.s,height};
      entry.start=Math.min(entry.start,a.s);entry.end=Math.max(entry.end,b.s);obstacles.set(building.id,entry);
    }
  }
  result[route.id]=[...obstacles.values()].map(entry=>{
    entry.start-=3;entry.end+=3; // Include the endpoint frames and deck overhang.
    entry.approach=Math.max(0,1.5*(entry.height-Math.min(base(entry.start),base(entry.end)))/.045);
    if(!entry.approach)return entry;
    for(const station of route.stations) {
      const half=(station.length??route.platformLength)/2+45;
      if(entry.start-entry.approach<station.s+half&&entry.end+entry.approach>station.s-half)
        throw Error(`Clearance for building ${entry.buildingId} would move station ${station.name}`);
    }
    if(entry.start-entry.approach<0||entry.end+entry.approach>route.length)throw Error('Clearance would move a route junction');
    return entry;
  });
}
writeFileSync(new URL('../web/static/world/assets/rail/clearance-data.js',import.meta.url),
  '// Generated by tools/index-rail-clearance.mjs from the vendored building tiles.\nexport const railClearance = '+JSON.stringify(result)+';\n');
console.log(`Indexed ${Object.values(result).flat().length} rail/building footprints.`);
