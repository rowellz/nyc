// Repair platform assignments in an existing snapshot without fetching map data.
// Only move a platform to a nearby, level track which better matches its source
// layer; preserve the already solved track graph and its grades.
import {readFileSync,writeFileSync} from 'node:fs';
import {mappedData} from '../web/static/world/assets/rail/mapped-data.js';
import {nearestRailPoint,railStructure} from '../web/static/world/assets/rail/map-compiler.js';
const routes=mappedData.routes.map(r=>({data:r,points:r.points.map(([x,z,y,s])=>({x,z,y,s}))}));
let moved=0;
for(const original of routes)for(const station of [...original.data.stations]) {
 const polygon=station.source?.polygon,tags=station.source?.tags;
 if(!polygon||tags?.layer===undefined||station.y>=0)continue;
 const x=polygon.reduce((n,p)=>n+p[0],0)/polygon.length,z=polygon.reduce((n,p)=>n+p[1],0)/polygon.length;
 const target=railStructure({tunnel:'yes',layer:tags.layer}).target,old=nearestRailPoint(original.points,x,z);
 if(Math.abs(old.y-target)<3.5)continue;
 let best=null;
 for(const route of routes) {
  const q=nearestRailPoint(route.points,x,z);
  if(q.distance>Math.min(35,old.distance+3)||Math.abs(q.y-target)>=Math.abs(old.y-target)-3.5)continue;
  if(q.s<station.length/2+10||q.s>route.points.at(-1).s-station.length/2-10)continue;
  if(route.points.some(p=>Math.abs(p.s-q.s)<station.length/2+8&&Math.abs(p.y-q.y)>.00001))continue;
  const score=Math.abs(q.y-target)*100+q.distance;
  if(!best||score<best.score)best={route,q,score};
 }
 if(!best)continue;
 const {route,q}=best;
 original.data.stations.splice(original.data.stations.indexOf(station),1);
 route.data.stations.push({...station,s:q.s,x:q.x,z:q.z,y:q.y,offset:Math.sign(q.offset||1)*Math.max(3.1,Math.min(6,Math.abs(q.offset)))});
 moved++;
}
// The original nearest-track deduplication could discard a second platform
// directly below the first. Recover those retained OSM polygons at their own
// mapped layer, without changing track grades or inventing extra storeys.
const features=JSON.parse(readFileSync(new URL('../web/static/world/assets/rail/map-features.json',import.meta.url))),present=new Set(routes.flatMap(r=>r.data.stations.map(s=>s.id)));
let recovered=0;
for(const platform of features.platforms) {
 if(present.has(platform.id)||platform.tags.layer===undefined)continue;
 const peers=routes.flatMap(r=>r.data.stations).filter(s=>s.source?.stationId===platform.stationId);
 if(!peers.length)continue;
 const target=railStructure({...platform.tags,...(Number(platform.tags.layer)<0?{tunnel:'yes'}:{})}).target;
 if(target>=0||peers.some(s=>Math.abs(s.y-target)<3.5))continue;
 let best=null;
 for(const route of routes) {
  const q=nearestRailPoint(route.points,platform.x,platform.z);if(q.distance>15||Math.abs(q.y-target)>.25)continue;
  const half=Math.min(100,q.s-12,route.points.at(-1).s-q.s-12);if(half<60)continue;
  if(route.points.some(p=>Math.abs(p.s-q.s)<half+4&&Math.abs(p.y-q.y)>.001))continue;
  if(!best||q.distance<best.q.distance)best={route,q,half};
 }
 if(!best)continue;
 const {route,q,half}=best;route.data.stations.push({id:platform.id,name:platform.name,s:q.s,x:q.x,z:q.z,y:q.y,offset:Math.sign(q.offset||1)*Math.max(3.1,Math.min(6,Math.abs(q.offset))),length:half*2,source:{id:platform.id,stationId:platform.stationId,name:platform.name,polygon:platform.polygon,tags:platform.tags}});present.add(platform.id);recovered++;
}
mappedData.stats.platforms=routes.reduce((n,r)=>n+r.data.stations.length,0);
for(const r of routes)r.data.stations.sort((a,b)=>a.s-b.s);
writeFileSync(new URL('../web/static/world/assets/rail/mapped-data.js',import.meta.url),'// Generated by tools/import-railways.mjs; platform levels refined from retained source tags. © OpenStreetMap contributors, ODbL 1.0.\nexport const mappedData = '+JSON.stringify(mappedData)+';\n');
console.log(`Corrected ${moved} platform assignments to their mapped track level.`);
console.log(`Recovered ${recovered} omitted stacked platform polygons from retained map data.`);
